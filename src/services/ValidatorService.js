// ROLLCALL: every epoch (1008 BTC blocks, 30 on regtest) each validator signs
// a message over that epoch's ledger_hash; the elected leader publishes the
// collected signatures on DOGE, and the BTC indexer closes the epoch and
// evicts a staking source absent for K=2 consecutive rolled epochs. Every
// ROLLCALL payload exceeds the 76-byte OP_RETURN cap, so it always rides the
// chunked two-phase P2SH lane - two transactions, ~0.003 DOGE each - which is
// where the per-call DOGE cost below comes from. It spends from the same
// publisher wallet anchors already use; no separate wallet or key.
const ROLLCALL_DOGE_COST_PER_CALL = 0.006
// BTC blocks per ROLLCALL epoch, network-keyed. An absence read only ever
// returns absent epochs, so two rows are a true back-to-back streak only when
// their epoch_height values are exactly one epoch apart; any other gap means
// a rolled (present) epoch fell between them, however close the rows sit in
// the array.
const ROLLCALL_EPOCH_BLOCKS = { regtest: 30, testnet: 1008, mainnet: 1008 }
const ROLLCALL_EPOCH_BLOCKS_DEFAULT = 1008

// Lazy: the SDK pulls in the whole bitcoinjs stack, and every validator
// subcommand that does not touch a wallet (status) should not pay for it.
function loadSdk() {
    return require('@dankest-llc/xchain-sdk')
}

// Generate a fresh single-key wallet on the named SDK network, or import one
// from a WIF. Returns address + public key + WIF; the caller decides where the
// WIF is written and it is never printed.
function makeCoinWallet(sdkNetwork, wif) {
    const { XChainSDK } = loadSdk()
    const sdk  = new XChainSDK({ network: sdkNetwork })
    const keys = wif ? sdk.wallet.importWIF(wif) : sdk.wallet.generateKeyPair()
    return {
        address:   sdk.wallet.deriveAddress(keys.publicKey),
        pubkeyHex: keys.publicKeyHex,
        wif:       keys.wif
    }
}

// Read a secret from the CONTROLLING TERMINAL with echo off. /dev/tty rather
// than stdin, so a pasted multi-line block cannot race the prompt. Returns
// null when there is no terminal, so a non-interactive caller gets a clear
// error naming the env var instead of a hang.
function promptSecret(promptText) {
    const { execFileSync } = require('child_process')
    let fd
    try { fd = fs.openSync('/dev/tty', 'rs') } catch { return null }
    let echoOff = false
    try { execFileSync('stty', ['-echo'], { stdio: [fd, 'ignore', 'ignore'] }); echoOff = true } catch { /* not a tty */ }
    process.stderr.write(promptText)
    const buf = Buffer.alloc(1)
    let out = ''
    try {
        for (;;) {
            let n = 0
            try { n = fs.readSync(fd, buf, 0, 1, null) }
            catch (e) { if (e.code === 'EAGAIN') continue; throw e }
            if (n === 0) break
            const ch = buf.toString('utf8')
            if (ch === '\n' || ch === '\r') break
            if (ch === '\u0003') { out = ''; break }
            if (ch === '\u007f') { out = out.slice(0, -1); continue }
            out += ch
        }
    } finally {
        if (echoOff) { try { execFileSync('stty', ['echo'], { stdio: [fd, 'ignore', 'ignore'] }) } catch { /* best effort */ } }
        process.stderr.write('\n')
        try { fs.closeSync(fd) } catch { /* closed */ }
    }
    return out.trim()
}

// Resolve an operator-supplied WIF for one wallet: the env var first (the
// non-interactive path), then a hidden prompt. Throws when asked to import and
// neither is available, because silently generating instead would strand the
// coin the operator already funded at their own address.
function resolveImportedWif(label, envName, wantImport) {
    const fromEnv = process.env[envName]
    if (fromEnv) return fromEnv
    if (!wantImport) return null
    const typed = promptSecret('WIF for the ' + label + ' wallet (input hidden): ')
    if (!typed) {
        throw new Error('no WIF supplied for the ' + label + ' wallet. Type it at the prompt on a terminal, ' +
            'or set ' + envName + ' in the environment (never on the command line).')
    }
    return typed
}

// Parse a KEY=VALUE sidecar into an object. Comments and blank lines skipped.
function parseEnvText(text) {
    const out = {}
    for (const line of String(text || '').split(/\r?\n/)) {
        if (!line || line.startsWith('#')) continue
        const eq = line.indexOf('=')
        if (eq <= 0) continue
        out[line.substring(0, eq).trim()] = line.substring(eq + 1).trim()
    }
    return out
}

