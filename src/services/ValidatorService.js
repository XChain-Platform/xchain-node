// Strip comments before scanning a signer module's source, so a doc comment
// that merely mentions `broadcast(...)` (the generated template's own
// contract comment does exactly that, right above its module.exports) cannot
// be mistaken for the export itself.
function stripJsComments(src) {
    return String(src || '').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
}

// Whether a signer module's module.exports names a `broadcast` export. Static
// only: this CLI never requires an operator-supplied signer file just to ask
// it a question, because that module's top-level code is meant to run inside
// the hub container (with its own env, its own SDK session) - not at
// `validator status` time, under whatever privileges ran the CLI. Returns
// null when there is no file to check.
function signerModuleExportsBroadcast(signerFilePath) {
    if (!signerFilePath || !isRegularFile(signerFilePath)) return null
    let src
    try { src = fs.readFileSync(signerFilePath, 'utf8') } catch { return null }
    const stripped = stripJsComments(src)
    if (/\bexports\.broadcast\s*=/.test(stripped)) return true
    // Scope the object-literal form (`broadcast(payload) {...}` or
    // `broadcast: ...` inside `module.exports = { ... }`) to text from the
    // LAST module.exports onward, so a `broadcast` named only in prose or a
    // helper earlier in the file cannot false-positive.
    const idx = stripped.lastIndexOf('module.exports')
    const tail = idx >= 0 ? stripped.slice(idx) : ''
    return /\bbroadcast\s*(?:\(|:)/.test(tail)
}

// The network this validator was initialized for: recorded on init, derived
// from the P2P port for installs that predate the field.
function resolveNetwork(opts, p2pPort) {
    const explicit = opts.network ? String(opts.network).toLowerCase() : null
    if (explicit && !COIN_NETWORKS[explicit]) {
        throw new Error('--network must be one of mainnet, testnet, regtest (got ' + opts.network + ')')
    }
    if (explicit) return explicit
    return NETWORK_BY_P2P_PORT[p2pPort] || null
}

// ASN.1 DER prefixes for Ed25519 (same as xchain-hub/src/ValidatorIdentity.js),
// so the pubkey we print matches what the hub derives from the same seed.
const PKCS8_ED25519_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex')
const SPKI_ED25519_PREFIX  = Buffer.from('302a300506032b6570032100', 'hex')

// Derive the 64-hex public key from a 64-hex Ed25519 seed.
function pubkeyFromSeedHex(seedHex) {
    const pkcs8 = Buffer.concat([PKCS8_ED25519_PREFIX, Buffer.from(seedHex, 'hex')])
    const priv  = crypto.createPrivateKey({ key: pkcs8, format: 'der', type: 'pkcs8' })
    const spki  = crypto.createPublicKey(priv).export({ format: 'der', type: 'spki' })
    return spki.subarray(SPKI_ED25519_PREFIX.length).toString('hex')
}

// Default capability config. MIN_STAKE thresholds mirror the indexer's
// authoritative governance config; the per-capability blocks satisfy the hub's
// self-tests. Operators tune capabilities.json after init (e.g. real RPC URLs).
function defaultCapabilityConfig(capabilities, wallets) {
    const enabled = new Set(capabilities)
    // The publisher block is filled from the DOGE wallet when init made one;
    // otherwise the placeholders stay and the operator edits them by hand.
    const dogeAddress = (wallets && wallets.dogeAddress) || 'REPLACE_WITH_DOGE_ADDRESS'
    const dogeWallet  = (wallets && wallets.dogeAddress) ? (SIGNER_CONTAINER_DIR + '/.env') : 'REPLACE_WITH_DOGE_WALLET_PATH'
    const allCaps = ['price', 'cross_chain', 'oracle_publish', 'attestation']
    return {
        // These MUST equal src/coins/BTC.js STAKING.CAPABILITIES MIN_STAKE
        // (the federation-uniform floors every hub sends the indexer as the
        // qualifying threshold). The hub asserts this at startup and refuses to
        // boot on mainnet/testnet if they diverge; cross_chain was 1000 here vs
        // the canonical 5000 for a while, which is the footgun that assert closes.
        CAPABILITIES: {
            price:          { MIN_STAKE: '1000.00000000' },
            cross_chain:    { MIN_STAKE: '5000.00000000' },
            oracle_publish: { MIN_STAKE: '500.00000000'  },
            attestation:    { MIN_STAKE: '1000.00000000' },
            // full_node is absent from allCaps below (a NODEPROOF tier, not an
            // opt-in capability) but its threshold still belongs here: omitting
            // one threshold makes the hub refuse to build ANY capability
            // snapshot, so every capability reads N=0 and the transport signer
            // set stays empty. Fail-closed, because a locally-chosen threshold
            // could qualify different validator sets for one round and fork.
            full_node:      { MIN_STAKE: '2000.00000000' }
        },
        // Capabilities the operator opted OUT of (qualified but won't serve).
        DISABLED_CAPABILITIES: allCaps.filter(c => !enabled.has(c)),
        // Self-test config blocks (presence-checked by the hub; live probing
        // happens during normal operation).
        price:          { sources: ['coingecko'], fiats: ['USD'] },
        cross_chain:    { chains: { BTC: { rpc: 'http://node:8332' } } },
        oracle_publish: { doge_address: dogeAddress, doge_wallet: dogeWallet },
        attestation:    { providers: {} }
    }
}

