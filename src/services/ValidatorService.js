// Create the empty node_modules directory the SDK mount lands on (see
// SIGNER_MODULES_DIR). Idempotent, and re-checked at mount time rather than
// only at init, so a config directory written before this existed still starts.
// An empty node_modules on the host is harmless outside the container: node
// keeps walking up the tree when a package is not found in it.
function ensureSignerModulesMountpoint() {
    if (!fs.existsSync(SIGNER_MODULES_DIR)) fs.mkdirSync(SIGNER_MODULES_DIR, { recursive: true })
}

// Host directory to mount at SIGNER_CONTAINER_DIR, or null. An operator who
// set XCHAIN_NODE_HUB_SIGNER_DIR runs their own signer and wins; the generated
// one is the default for everyone else. The signer requires the SDK, which is
// resolved from a node_modules mounted BESIDE it (ModuleService mounts this
// package's own node_modules there), so init never has to run npm.
function getSignerMountDir() {
    if (process.env.XCHAIN_NODE_HUB_SIGNER_DIR) return null
    if (!signerDirExists()) return null
    ensureSignerModulesMountpoint()
    return SIGNER_DIR
}

// The signer.js file actually in force: an operator-supplied module wins
